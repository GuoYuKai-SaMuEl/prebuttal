class ConfigError(Exception):
    """Raised for unreadable or invalid configuration."""


@dataclass
class AgentSpec:
    command: list[str]
    stdin: bool = True

    def describe(self) -> str:
        return " ".join(self.command) + ("  (prompt on stdin)" if self.stdin else "")


@dataclass
class ReviewerConfig:
    id: str
    persona: str
    backend: str = "auto"
    model: str = ""
    temperature: float = 0.4
    seed: int | None = None  # None -> default seed + reviewer index


@dataclass
class ACConfig:
    persona: str = "area_chair"
    backend: str = "auto"
    model: str = ""
    temperature: float = 0.3


@dataclass
class RunConfig:
    venue: str = "neurips"
    seed: int = 42
    budget_chars: int = 120_000
    compress: bool = False  # LLM-summarize elided sections instead of truncating
    max_tokens: int = 6000
    est_completion_tokens: int = 2500
    timeout_s: int = 900
    retries: int = 2
    reviewers: list[ReviewerConfig] = field(default_factory=list)
    ac: ACConfig = field(default_factory=ACConfig)
    agents: dict[str, AgentSpec] = field(default_factory=dict)
    relay_dir: str = "relay"
    relay_timeout_s: int = 1800
    pricing: dict[str, tuple[float, float]] = field(default_factory=lambda: dict(DEFAULT_PRICING))
    repo_url: str = "https://github.com/GuoYuKai-SaMuEl/prebuttal"
    config_path: str | None = None


PERSONA_CYCLE = ["senior_kind", "adversarial", "detail_obsessive"]
PERSONA_TEMPS = [0.4, 0.7, 0.5]


def default_reviewers(n: int = 3) -> list[ReviewerConfig]:
    n = max(1, min(n, 5))
    out = []
    for i in range(n):
        persona = PERSONA_CYCLE[i % 3]
        temp = PERSONA_TEMPS[i % 3] + (0.1 if i >= 3 else 0.0)
        out.append(
            ReviewerConfig(id=f"R{i + 1}", persona=persona, backend="auto", temperature=temp)
        )
    return out


def _as_list(x: Any) -> list[str]:
    if x is None:
        return []
    if isinstance(x, str):
        return shlex.split(x)
    return [str(v) for v in x]


def load_config(path: str | Path | None = None) -> RunConfig:
    cfg = RunConfig(reviewers=default_reviewers(3))
    if path is None:
        candidate = Path(CONFIG_FILENAME)
        if not candidate.is_file():
            return cfg
        path = candidate
    path = Path(path)
    if not path.is_file():
        raise ConfigError(f"config file not found: {path}")
    try:
        raw = tomllib.loads(path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as e:  # pragma: no cover - message passthrough
        raise ConfigError(f"invalid TOML in {path}: {e}") from e
    cfg.config_path = str(path)

    d = raw.get("default", {})
    if "venue" in d:
        cfg.venue = str(d["venue"])
    if cfg.venue not in VENUE_KEYS:
        raise ConfigError(
            f"unknown venue '{cfg.venue}' in {path} — supported: {', '.join(VENUE_KEYS)}"
        )
    cfg.seed = int(d.get("seed", cfg.seed))
    cfg.budget_chars = int(d.get("budget_chars", cfg.budget_chars))
    cfg.compress = bool(d.get("compress", cfg.compress))
    cfg.max_tokens = int(d.get("max_tokens", cfg.max_tokens))
    cfg.est_completion_tokens = int(d.get("est_completion_tokens", cfg.est_completion_tokens))
    cfg.timeout_s = int(d.get("timeout_s", cfg.timeout_s))
    cfg.retries = int(d.get("retries", cfg.retries))

    reviewers: list[ReviewerConfig] = []
    seen_ids: set[str] = set()
    for entry in raw.get("reviewer", []):
        rid = str(entry.get("id", f"R{len(reviewers) + 1}"))
        if rid in seen_ids:
            raise ConfigError(f"duplicate reviewer id '{rid}' in {path}")
        seen_ids.add(rid)
        reviewers.append(
            ReviewerConfig(
                id=rid,
                persona=str(entry.get("persona", "senior_kind")),
                backend=str(entry.get("backend", "auto")),
                model=str(entry.get("model", "") or ""),
                temperature=float(entry.get("temperature", 0.4)),
            )
        )
    if reviewers:
        if not 1 <= len(reviewers) <= 5:
            raise ConfigError(f"expected 1-5 [[reviewer]] entries, got {len(reviewers)}")
        cfg.reviewers = reviewers

    ac = raw.get("ac", {})
    if ac:
        cfg.ac = ACConfig(
            persona=str(ac.get("persona", "area_chair")),
            backend=str(ac.get("backend", "auto")),
            model=str(ac.get("model", "") or ""),
            temperature=float(ac.get("temperature", 0.3)),
        )

    for name, spec in raw.get("agents", {}).items():
        cfg.agents[str(name)] = AgentSpec(
            command=_as_list(spec.get("command")), stdin=bool(spec.get("stdin", True))
        )

    relay = raw.get("relay", {})
    if relay:
        cfg.relay_dir = str(relay.get("dir", cfg.relay_dir))
        cfg.relay_timeout_s = int(relay.get("timeout_s", cfg.relay_timeout_s))

    for model, prices in raw.get("pricing", {}).items():
        cfg.pricing[str(model)] = (
            float(prices.get("in", 0.0)),
            float(prices.get("out", 0.0)),
        )

    share = raw.get("share", {})
    if "repo_url" in share:
        cfg.repo_url = str(share["repo_url"])

    return cfg


def reviewer_seed(cfg: RunConfig, rcfg: ReviewerConfig, index: int) -> int:
    return rcfg.seed if rcfg.seed is not None else cfg.seed + index + 1


BACKEND_ENV = "PREBUTTAL_BACKEND"


def env_backend() -> str | None:
    """Backend forced for all roles via $PREBUTTAL_BACKEND (empty = unset).

    Precedence: --backend flag > PREBUTTAL_BACKEND > prebuttal.toml > auto.
    Lets a host agent pin e.g. ``relay`` once for its whole environment.
    """
    value = os.environ.get(BACKEND_ENV, "").strip()
    return value or None


def apply_overrides(
    cfg: RunConfig,
    *,
    venue: str | None = None,
    seed: int | None = None,
    backend: str | None = None,
    model: str | None = None,
    reviewers_count: int | None = None,
) -> RunConfig:
    """Return a copy of cfg with CLI-flag overrides applied."""
    if venue is not None:
        if venue not in VENUE_KEYS:
            raise ConfigError(f"unknown venue '{venue}' — supported: {', '.join(VENUE_KEYS)}")
        cfg.venue = venue
    if seed is not None:
        cfg.seed = seed
    if reviewers_count is not None and reviewers_count != len(cfg.reviewers):
        if not 1 <= reviewers_count <= 5:
            raise ConfigError("--reviewers must be between 1 and 5")
        cfg.reviewers = default_reviewers(reviewers_count)
    if backend is not None:
        cfg.reviewers = [replace(r, backend=backend) for r in cfg.reviewers]
        cfg.ac = replace(cfg.ac, backend=backend)
    if model is not None:
        cfg.reviewers = [replace(r, model=model) for r in cfg.reviewers]
        cfg.ac = replace(cfg.ac, model=model)
    return cfg
