"""Regenerate the GitHub Pages report pages under ``site/reports/``.

The landing page (``site/index.html``) is hand-written; this script only
re-renders the share pages for curated sample runs from their stored
``report.json`` and copies the synthetic sample report in, so the site
matches whatever the tool actually produced. Site pages get the GoatCounter
snippet; the tool's own share output never does.

Usage::

    python scripts/build_site.py [runs_dir]

``runs_dir`` defaults to ``~/.prebuttal/runs`` (respect PREBUTTAL_HOME).
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from prebuttal.report import report_from_dict
from prebuttal.share import render_share_html
from prebuttal.venues import get_venue

REPO_URL = "https://github.com/GuoYuKai-SaMuEl/prebuttal"

# (site filename, glob over run dir names, banner) — first match with
# parseable reviews wins, so re-running after a better run upgrades the sample.
# Curation rule: real papers are only shown when the simulated panel was
# favorable — a harsh AI review of someone's published work is not ours to
# publish. The "what a weak paper gets" example is a synthetic paper
# (examples/weak-paper/), fictional and deliberately flawed.
REMOVAL = f'Authors who want this page removed: <a href="{REPO_URL}/issues">open an issue</a>.'


def _real_paper_banner(arxiv_id: str, authors: str, extra: str = "") -> str:
    # Curated papers are CC BY 4.0 on arXiv: attribute, link the license,
    # and say what was changed (AI-generated summaries / short quotes).
    mid = f" {extra}" if extra else ""
    return (
        "Unofficial demo: an AI-simulated review of "
        f'<a href="https://arxiv.org/abs/{arxiv_id}">arXiv:{arxiv_id}</a> by {authors}, '
        'licensed <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>.'
        f"{mid} "
        "Summaries and short quotes below were generated by AI models from the paper "
        "and may contain errors; generated only to show what Prebuttal outputs. Not "
        "written, reviewed or endorsed by the authors, and not an assessment of the "
        "work's merit. " + REMOVAL
    )


SYNTHETIC_BANNER = (
    "Synthetic example: a fictional, deliberately flawed paper written for this demo "
    f'(<a href="{REPO_URL}/tree/main/examples/weak-paper">examples/weak-paper</a>). '
    "No real authors, methods or results."
)

# The Mamba pair is a revision round: same panel (claude sonnet · codex ·
# gemini-3.8-flash, AC claude opus), same seed, over both arXiv versions —
# v1 is the ICLR 2024-rejected submission, v2 the revision accepted at
# COLM 2024. The id prefixes pin the 2026-10-26 runs so the "*mamba*"
# glob can't silently drift to a newer run.
CURATED: list[tuple[str, str, str]] = [
    (
        "mamba-v1.html",
        "20261026-0110*",
        _real_paper_banner(
            "2312.00752v1",
            "Albert Gu and Tri Dao",
            "This is arXiv v1 (December 2023) — the version rejected at ICLR 2024.",
        ),
    ),
    (
        "mamba-v2.html",
        "20261026-0114*",
        _real_paper_banner(
            "2312.00752v2",
            "Albert Gu and Tri Dao",
            "This is arXiv v2 (May 2024) — the revised version, accepted at COLM 2024.",
        ),
    ),
    (
        "dpo.html",
        "*direct-preference*",
        _real_paper_banner("2305.18290", "Rafael Rafailov, Archit Sharma, Eric Mitchell, et al."),
    ),
    ("weak.html", "*globalgate*", SYNTHETIC_BANNER),
]

_BANNER_START = "<!-- site-banner -->"
_BANNER_END = "<!-- /site-banner -->"


def with_banner(html: str, banner: str) -> str:
    """Insert (or replace) the curation banner right after the page header."""
    if _BANNER_START in html:
        head, rest = html.split(_BANNER_START, 1)
        html = head + rest.split(_BANNER_END, 1)[1]
    block = (
        f'{_BANNER_START}<div style="background:#fff7ed;border:1px solid #fed7aa;'
        f'border-radius:10px;padding:10px 14px;margin:14px 0;font-size:13px;color:#9a3412">'
        f"{banner}</div>{_BANNER_END}"
    )
    return html.replace("</header>", "</header>\n  " + block, 1)


# Cookieless page-view counter for the published site only. The tool's own
# share pages (prebuttal/share.py) must never carry it: those are the user's.
_ANALYTICS_START = "<!-- site-analytics -->"
_ANALYTICS_END = "<!-- /site-analytics -->"
ANALYTICS = (
    '<script data-goatcounter="https://prebuttal.goatcounter.com/count"\n'
    '        async src="//gc.zgo.at/count.js"></script>'
)


def with_analytics(html: str) -> str:
    """Insert (or refresh) the site's GoatCounter snippet before ``</body>``."""
    if _ANALYTICS_START in html:
        head, rest = html.split(_ANALYTICS_START, 1)
        html = head.rstrip(" ") + rest.split(_ANALYTICS_END, 1)[1].lstrip("\n")
    block = f"{_ANALYTICS_START}\n{ANALYTICS}\n{_ANALYTICS_END}\n"
    return html.replace("</body>", block + "</body>", 1)


def find_report(runs_dir: Path, pattern: str) -> dict | None:  # type: ignore[type-arg]
    candidates = sorted(p for p in runs_dir.glob(pattern) if (p / "report.json").exists())
    for run_dir in reversed(candidates):  # newest first
        d = json.loads((run_dir / "report.json").read_text(encoding="utf-8"))
        if any(r.get("parse_ok") for r in d.get("reviewers", [])):
            return d
    return None


def venue_key(d: dict) -> str:  # type: ignore[type-arg]
    v = d["venue"]
    return v["key"] if isinstance(v, dict) else v


def main() -> int:
    home = os.environ.get("PREBUTTAL_HOME") or os.path.expanduser("~/.prebuttal")
    runs_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(home) / "runs"
    out_dir = REPO / "site" / "reports"
    out_dir.mkdir(parents=True, exist_ok=True)

    for name, pattern, banner in CURATED:
        target = out_dir / name
        d = find_report(runs_dir, pattern)
        if d is None:
            if target.exists():  # keep the published page, refresh its banner
                old = target.read_text(encoding="utf-8")
                target.write_text(with_analytics(with_banner(old, banner)), encoding="utf-8")
                print(f"[site] no run for {pattern} — kept {name}, banner refreshed")
            else:
                print(f"[site] no usable run for {pattern} — skipping {name}")
            continue
        venue = get_venue(venue_key(d))
        html = render_share_html(report_from_dict(d), venue, REPO_URL)
        target.write_text(with_analytics(with_banner(html, banner)), encoding="utf-8")
        title = d["paper"]["title"][:60]
        print(f"[site] {name} <- {title!r} ({d['venue']})")

    sample = REPO / "examples" / "sample-report.html"
    if sample.exists():
        html = sample.read_text(encoding="utf-8")
        (out_dir / "sample.html").write_text(with_analytics(html), encoding="utf-8")
        print("[site] sample.html <- examples/sample-report.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
