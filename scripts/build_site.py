def _toml(value: object) -> str:
    if value == "":
        return "unset"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    if isinstance(value, (tuple, list)):
        return "[" + ", ".join(f'"{v}"' for v in value) + "]"
    return str(value)


